create table if not exists public.respostas_solicitacoes (
  id bigint generated by default as identity primary key,
  solicitacao_id bigint not null references public.solicitacoes(id) on delete cascade,
  mensagem text,
  anexos jsonb not null default '[]'::jsonb,
  criado_em timestamptz not null default now(),
  constraint resposta_tem_conteudo
    check (
      nullif(btrim(coalesce(mensagem, '')), '') is not null
      or jsonb_array_length(anexos) > 0
    )
);

create index if not exists idx_respostas_solicitacoes_solicitacao
  on public.respostas_solicitacoes (solicitacao_id, criado_em desc);

alter table public.respostas_solicitacoes enable row level security;

drop policy if exists "admin le respostas" on public.respostas_solicitacoes;
create policy "admin le respostas"
  on public.respostas_solicitacoes
  for select
  to authenticated
  using (true);

drop policy if exists "admin cria respostas" on public.respostas_solicitacoes;
create policy "admin cria respostas"
  on public.respostas_solicitacoes
  for insert
  to authenticated
  with check (true);

drop policy if exists "admin atualiza respostas" on public.respostas_solicitacoes;
create policy "admin atualiza respostas"
  on public.respostas_solicitacoes
  for update
  to authenticated
  using (true)
  with check (true);

drop policy if exists "admin exclui respostas" on public.respostas_solicitacoes;
create policy "admin exclui respostas"
  on public.respostas_solicitacoes
  for delete
  to authenticated
  using (true);

grant select, insert, update, delete
  on public.respostas_solicitacoes
  to authenticated;

grant usage, select
  on sequence public.respostas_solicitacoes_id_seq
  to authenticated;

-- Bucket público apenas para documentos enviados pelo mandato.
-- O cidadão recebe o link somente ao consultar o protocolo.
insert into storage.buckets (id, name, public, file_size_limit)
values ('documentos-respostas', 'documentos-respostas', true, 10485760)
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit;

drop policy if exists "admin envia documentos de resposta" on storage.objects;
create policy "admin envia documentos de resposta"
  on storage.objects
  for insert
  to authenticated
  with check (bucket_id = 'documentos-respostas');

drop policy if exists "admin atualiza documentos de resposta" on storage.objects;
create policy "admin atualiza documentos de resposta"
  on storage.objects
  for update
  to authenticated
  using (bucket_id = 'documentos-respostas')
  with check (bucket_id = 'documentos-respostas');

drop policy if exists "admin exclui documentos de resposta" on storage.objects;
create policy "admin exclui documentos de resposta"
  on storage.objects
  for delete
  to authenticated
  using (bucket_id = 'documentos-respostas');

-- Mantém a consulta pública atual intacta e cria uma segunda RPC só para respostas.
create or replace function public.consulta_publica_respostas_protocolo(
  p_protocolo text
)
returns table (
  mensagem text,
  anexos jsonb,
  criado_em timestamptz
)
language sql
security definer
set search_path = public
as $$
  select
    r.mensagem,
    r.anexos,
    r.criado_em
  from public.respostas_solicitacoes r
  inner join public.solicitacoes s
    on s.id = r.solicitacao_id
  where s.protocolo = p_protocolo
  order by r.criado_em desc;
$$;

revoke all
  on function public.consulta_publica_respostas_protocolo(text)
  from public;

grant execute
  on function public.consulta_publica_respostas_protocolo(text)
  to anon, authenticated;
