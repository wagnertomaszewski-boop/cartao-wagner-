-- Estrutura EXCLUSIVA para homologação isolada, sem dados reais.
-- Aplicar SOMENTE em branch Neon dedicada, nunca na branch production.
BEGIN;
CREATE SCHEMA IF NOT EXISTS fiscalizacao_homologacao;
CREATE TABLE IF NOT EXISTS fiscalizacao_homologacao.solicitacoes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status text NOT NULL DEFAULT 'Recebida',
  encaminhado_prefeitura_em date,
  protocolo_prefeitura varchar(120),
  CONSTRAINT data_nao_futura CHECK (encaminhado_prefeitura_em IS NULL OR encaminhado_prefeitura_em <= CURRENT_DATE),
  CONSTRAINT protocolo_exige_data CHECK (protocolo_prefeitura IS NULL OR encaminhado_prefeitura_em IS NOT NULL),
  CONSTRAINT protocolo_nao_vazio CHECK (protocolo_prefeitura IS NULL OR length(btrim(protocolo_prefeitura)) > 0)
);
CREATE TABLE IF NOT EXISTS fiscalizacao_homologacao.solicitacoes_fiscalizacao_historico (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitacao_id bigint NOT NULL REFERENCES fiscalizacao_homologacao.solicitacoes(id) ON DELETE RESTRICT,
  tipo text NOT NULL CHECK (tipo IN ('encaminhamento','cobranca','retorno','verificacao')),
  descricao text NOT NULL CHECK (char_length(btrim(descricao)) BETWEEN 5 AND 2000),
  protocolo_referencia varchar(120),
  registrado_em timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT protocolo_referencia_nao_vazio CHECK (protocolo_referencia IS NULL OR length(btrim(protocolo_referencia)) > 0)
);
CREATE INDEX IF NOT EXISTS fiscalizacao_homologacao_hist_consulta_idx
 ON fiscalizacao_homologacao.solicitacoes_fiscalizacao_historico(solicitacao_id, registrado_em DESC);
-- Nenhuma permissão para acesso anônimo ou roles públicas.
REVOKE ALL ON SCHEMA fiscalizacao_homologacao FROM PUBLIC;
REVOKE ALL ON ALL TABLES IN SCHEMA fiscalizacao_homologacao FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA fiscalizacao_homologacao FROM PUBLIC;
COMMIT;
